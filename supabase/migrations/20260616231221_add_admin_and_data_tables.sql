-- 1. Create a custom role type and add role column to profiles table
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'user_role') THEN
    CREATE TYPE user_role AS ENUM ('user', 'admin');
  END IF;
END $$;

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS role TEXT DEFAULT 'user' CHECK (role IN ('user', 'admin'));

-- 2. Create gallery table
CREATE TABLE IF NOT EXISTS public.gallery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  src TEXT NOT NULL,
  alt TEXT DEFAULT '',
  caption TEXT DEFAULT '',
  span TEXT DEFAULT 'default' CHECK (span IN ('default', 'wide', 'tall')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create projects table
CREATE TABLE IF NOT EXISTS public.projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  status TEXT DEFAULT 'Ongoing' CHECK (status IN ('Ongoing', 'Completed', 'Upcoming')),
  icon TEXT DEFAULT 'Info',
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Create magazine table
CREATE TABLE IF NOT EXISTS public.magazine (
  id INT PRIMARY KEY DEFAULT 1 CHECK (id = 1), -- only one row allowed
  eyebrow TEXT DEFAULT 'Our Story in Print',
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  cover_image TEXT NOT NULL,
  download_url TEXT DEFAULT '#',
  read_url TEXT DEFAULT '#',
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable Row Level Security (RLS) on new tables
ALTER TABLE public.gallery ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.magazine ENABLE ROW LEVEL SECURITY;

-- Helper function to check if the user is an admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Drop existing policies if they exist to avoid duplication errors
DROP POLICY IF EXISTS "Anyone can view gallery" ON public.gallery;
DROP POLICY IF EXISTS "Admins can manage gallery" ON public.gallery;
DROP POLICY IF EXISTS "Anyone can view projects" ON public.projects;
DROP POLICY IF EXISTS "Admins can manage projects" ON public.projects;
DROP POLICY IF EXISTS "Anyone can view magazine" ON public.magazine;
DROP POLICY IF EXISTS "Admins can manage magazine" ON public.magazine;

-- Create policies for gallery
CREATE POLICY "Anyone can view gallery" ON public.gallery FOR SELECT USING (true);
CREATE POLICY "Admins can manage gallery" ON public.gallery FOR ALL USING (public.is_admin());

-- Create policies for projects
CREATE POLICY "Anyone can view projects" ON public.projects FOR SELECT USING (true);
CREATE POLICY "Admins can manage projects" ON public.projects FOR ALL USING (public.is_admin());

-- Create policies for magazine
CREATE POLICY "Anyone can view magazine" ON public.magazine FOR SELECT USING (true);
CREATE POLICY "Admins can manage magazine" ON public.magazine FOR ALL USING (public.is_admin());

-- Grant permissions for roles on new tables
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;

GRANT ALL ON TABLE public.gallery TO postgres, service_role;
GRANT SELECT ON TABLE public.gallery TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.gallery TO authenticated;

GRANT ALL ON TABLE public.projects TO postgres, service_role;
GRANT SELECT ON TABLE public.projects TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.projects TO authenticated;

GRANT ALL ON TABLE public.magazine TO postgres, service_role;
GRANT SELECT ON TABLE public.magazine TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.magazine TO authenticated;
